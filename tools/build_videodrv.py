#!/usr/bin/env python3
"""Assemble src/core/videodrv.s into src/core/videodrv.h.

Needs GNU binutils for m68k (Debian/Ubuntu: binutils-m68k-linux-gnu).  The
generated header is committed, so normal builds do not.
"""
import os, subprocess, sys, tempfile

TOP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(TOP, "src", "core", "videodrv.s")
OUT = os.path.join(TOP, "src", "core", "videodrv.h")

def tool(name):
    return os.environ.get("M68K_" + name.upper(), "m68k-linux-gnu-" + name)

with tempfile.TemporaryDirectory() as tmp:
    obj, elf, binf = (os.path.join(tmp, n) for n in ("d.o", "d.elf", "d.bin"))
    subprocess.run([tool("as"), "-m68020", "--register-prefix-optional", "-o", obj, SRC], check=True)
    subprocess.run([tool("ld"), "-Ttext=0", "-o", elf, obj], check=True)
    subprocess.run([tool("objcopy"), "-O", "binary", "-j", ".text", elf, binf], check=True)
    syms = {}
    for line in subprocess.run([tool("nm"), elf], capture_output=True, text=True, check=True).stdout.splitlines():
        p = line.split()
        if len(p) == 3:
            syms[p[2]] = int(p[0], 16)
    code = open(binf, "rb").read()

lines = ["// Generated by tools/build_videodrv.py from videodrv.s - do not edit.",
         "#ifndef MACEMU_VIDEODRV_H", "#define MACEMU_VIDEODRV_H", "",
         "namespace macemu {", "",
         "static const unsigned kVideoDriverVBLHandler = 0x%X;" % syms["VBLHandler"],
         "static const unsigned char kVideoDriver[%d] = {" % len(code)]
for i in range(0, len(code), 16):
    lines.append("    " + ", ".join("0x%02X" % b for b in code[i:i + 16]) + ",")
lines += ["};", "", "} // namespace macemu", "", "#endif", ""]
open(OUT, "w").write("\n".join(lines))
print("%s: %d bytes" % (OUT, len(code)))
